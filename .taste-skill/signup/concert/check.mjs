import { chromium } from '../../../frontend/node_modules/playwright/index.mjs'
import { writeFile } from 'node:fs/promises'
const out = new URL('./', import.meta.url).pathname
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.routeWebSocket('**', () => {})
  await page.goto('http://127.0.0.1:5176/__signup-review.html')
  await page.getByLabel('Name', { exact: true }).fill('Maya Event')
  const color = () => page.locator('[data-page]').evaluate(el => el.style.getPropertyValue('--concert-color'))
  await page.mouse.move(180, 150)
  await page.waitForTimeout(750)
  const first = await color()
  await page.mouse.move(1250, 450)
  await page.waitForTimeout(750)
  const second = await color()
  if (!first || first === second) throw new Error('Pointer sweep did not change color')
  await page.mouse.click(1100, 140)
  const third = await color()
  if (third === second) throw new Error('Click did not trigger a new color')
  await page.waitForTimeout(300)
  await page.screenshot({ path: out + 'desktop-beat.png' })
  if (await page.getByLabel('Name', { exact: true }).inputValue() !== 'Maya Event') throw new Error('Light reset form data')
  const toggle = page.getByRole('button', { name: 'Concert lights' })
  await toggle.click()
  const stopped = await color()
  await page.mouse.move(100, 500)
  await page.mouse.click(1100, 140)
  if (await color() !== stopped) throw new Error('Paused lights still respond')
  if (await page.locator('.concert-lights').isVisible()) throw new Error('Paused lights still visible')
  await toggle.focus()
  await page.keyboard.press('Space')
  if (await toggle.getAttribute('aria-pressed') !== 'true') throw new Error('Keyboard toggle failed')
  const reduced = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
  await reduced.routeWebSocket('**', () => {})
  await reduced.goto('http://127.0.0.1:5176/__signup-review.html')
  await reduced.getByRole('heading', { name: 'Register your band.' }).waitFor()
  await reduced.mouse.move(80, 300)
  if (await reduced.locator('[data-page]').evaluate(el => el.style.getPropertyValue('--concert-color')) !== '') throw new Error('Reduced motion still tracks pointer')
  await reduced.mouse.click(200, 140)
  if (await reduced.locator('.concert-cursor').isVisible()) throw new Error('Reduced motion cursor wash visible')
  if (await reduced.evaluate(() => document.getAnimations().some(a => a.playState === 'running'))) throw new Error('Reduced motion still animates')
  await reduced.screenshot({ path: out + 'reduced-motion-mobile.png' })
  const phone = await browser.newPage({ viewport: { width: 320, height: 740 }, isMobile: true, hasTouch: true })
  await phone.routeWebSocket('**', () => {})
  await phone.goto('http://127.0.0.1:5176/__signup-review.html')
  await phone.getByRole('heading', { name: 'Register your band.' }).waitFor()
  await phone.touchscreen.tap(180, 140)
  if (!await phone.locator('[data-page]').evaluate(el => el.style.getPropertyValue('--concert-color'))) throw new Error('Touch tap did not change color')
  if (await phone.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Phone horizontal overflow')
  await phone.waitForTimeout(350)
  await phone.screenshot({ path: out + 'touch-beat-mobile.png' })
  if (errors.length) throw new Error(errors.join('\n'))
  const report = { result: 'pass', colors: [first, second, third], checks: ['pointer sweep changes pastel', 'click triggers next color and pulse', 'form data retained', 'lights toggle stops listeners', 'keyboard toggle', 'reduced motion has no pointer tracking or animation', 'touch tap responds', '320px no horizontal overflow'], consoleErrors: errors }
  await writeFile(out + 'checks.json', JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report, null, 2))
} finally { await browser.close() }
